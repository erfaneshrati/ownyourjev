"""Aggregate <task>/calibration.json (+ batch1.json) into results_v2/CALIBRATION.md and the paper's table/figures.

"Ours" uses the served predictions: batch size 1 where a task has batch1.json (int8 tasks re-predicted one request at a
time, calibrator refitted on batch-1 dev), otherwise the frozen test predictions (already batch 1 or fp32).
"""
from __future__ import annotations

import json
from pathlib import Path

from benchmarks.tasks import get_task
from benchmarks.v2.calibration_eval import ALLOWED_MULTICLASS
from benchmarks.v2.protocol import RESULTS

TASKS = ["sms_spam", "paws", "prompt_injections", "toxic_chat", "banking77", "clinc150", "ag_news",
         "financial_phrasebank", "emotion", "stsb", "sst5", "toxigen"]
NAMES = {"sms_spam": "SMS Spam", "paws": "PAWS", "prompt_injections": "Prompt Injections", "toxic_chat": "ToxicChat",
         "banking77": "Banking77", "clinc150": "CLINC150", "ag_news": "AG News", "financial_phrasebank": "Financial PhraseBank",
         "emotion": "Emotion", "stsb": "STS-B", "sst5": "SST-5", "toxigen": "ToxiGen"}
TYPES = {"sms_spam": "noul", "paws": "noul", "prompt_injections": "noul", "toxic_chat": "noul", "banking77": "choice",
         "clinc150": "choice", "ag_news": "choice", "financial_phrasebank": "choice", "emotion": "choice", "stsb": "score",
         "sst5": "score", "toxigen": "score"}
PAPER = Path(__file__).resolve().parents[2] / "paper"
KEYS = ("ece", "ace", "brier", "nll")


def load() -> list[dict]:
    rows = []
    for t in TASKS:
        p = RESULTS / t / "calibration.json"
        if not p.is_file():
            continue
        b1p = RESULTS / t / "batch1.json"
        b1 = json.loads(b1p.read_text())["heads"] if b1p.is_file() else {}
        for h, r in json.loads(p.read_text())["heads"].items():
            if "jev_raw" not in r:
                continue
            x = {"task": t, "head": h, "jev": r["jev_raw"], "jev_oracle": r["jev_oracle_recalibrated"], "batch1": h in b1}
            if h in b1:
                x["method"] = b1[h].get("calibration_method", "none")
                x["raw"] = b1[h]["calib_raw"]
                x["cal"] = b1[h].get("calib_calibrated", b1[h]["calib_raw"])
                x["oracle"] = r.get("ours_b1_oracle_recalibrated", r["ours_oracle_recalibrated"])
                x["batched_cal"] = r["ours_calibrated"]
            else:
                x.update(method=r["method"], raw=r["ours_raw"], cal=r["ours_calibrated"], oracle=r["ours_oracle_recalibrated"])
                if get_task(t).spec.parsed[h].type != "noul" and x["method"] not in ALLOWED_MULTICLASS:
                    # scored before the argmax-preserving rule (ToxiGen toxicity, vector): its dev-CV choice among the
                    # allowed methods is `none`, i.e. the raw row (see the task's CALIBRATION_NOTES.md)
                    x.update(method="none", cal=r["ours_raw"])
            rows.append(x)
    return rows


def label(x: dict) -> str:
    return NAMES[x["task"]] + (f" ({x['head']})" if x["task"] in ("toxic_chat", "toxigen") else "")


def markdown(rows: list[dict]) -> str:
    L = ["# Calibration vs Jev (generated by benchmarks/v2/calibration_report.py)", "",
         ("Calibrators were fitted on the 200 gold dev examples only (out-of-sample predictions of the deployed model) and frozen "
         "before one logged test scoring. Choice/Score heads use argmax-preserving calibrators only (none/temperature); Noul heads "
         "any monotone map, with decisions at the frozen threshold on the raw probability. Decisions and accuracy are unchanged by "
         "calibration. *Ours* = served predictions (batch size 1, `b1` marks tasks whose int8 test predictions were re-computed "
         "one request at a time). *Oracle* rows recalibrate each system by 5-fold CV on the test labels with the same allowed "
         "methods (an upper bound, identical for both systems). ECE: 10 equal-width bins, top-label; ACE: 10 equal-mass bins."), "",
         "| task | head | method | ECE ours raw | ECE ours cal. | ECE Jev | ACE ours / Jev | Brier ours / Jev | NLL ours / Jev | ECE oracle ours / Jev |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    w = {k: 0 for k in KEYS}
    for x in rows:
        c, j = x["cal"], x["jev"]
        for k in KEYS:
            w[k] += c[k] < j[k]

        def bb(a, b):
            return (f"**{a:.3f}** / {b:.3f}") if a < b else (f"{a:.3f} / **{b:.3f}**")
        L.append(f"| {NAMES[x['task']]}{' b1' if x['batch1'] else ''} | {x['head']} | {x['method']} | {x['raw']['ece']:.3f} | "
                 f"{'**' if c['ece'] < j['ece'] else ''}{c['ece']:.3f}{'**' if c['ece'] < j['ece'] else ''} | "
                 f"{'' if c['ece'] < j['ece'] else '**'}{j['ece']:.3f}{'' if c['ece'] < j['ece'] else '**'} | {bb(c['ace'], j['ace'])} | "
                 f"{bb(c['brier'], j['brier'])} | {bb(c['nll'], j['nll'])} | {x['oracle']['ece']:.3f} / {x['jev_oracle']['ece']:.3f} |")
    n = len(rows)
    L += ["", "Ours (calibrated) better than Jev on " + ", ".join(f"{k.upper()} {w[k]}/{n}" for k in KEYS) + " heads.", ""]
    b1 = [x for x in rows if x["batch1"]]
    if b1:
        L += ["Batched vs batch-1 calibrated ECE (int8 tasks): " + ", ".join(
            f"{label(x)} {x['batched_cal']['ece']:.3f} -> {x['cal']['ece']:.3f}" for x in b1), ""]
    return "\n".join(L)


def latex(rows: list[dict]) -> str:
    def cell(a, b):
        return (f"\\textbf{{{a:.3f}}}", f"{b:.3f}") if a < b else (f"{a:.3f}", f"\\textbf{{{b:.3f}}}")

    lines, last = [], None
    for x in rows:
        ty = TYPES[x["task"]]
        if last and ty != last:
            lines.append("\\midrule")
        last = ty
        c, j = x["cal"], x["jev"]
        e, ej = cell(c["ece"], j["ece"])
        br, bj = cell(c["brier"], j["brier"])
        nl, nj = cell(c["nll"], j["nll"])
        meth = {"none": "--", "temperature": "temp.", "platt": "Platt",
                "isotonic": "iso."}.get(x["method"], x["method"])
        lines.append(f"{label(x)} & {meth} & {x['raw']['ece']:.3f} & {e} & {ej} & {br} & {bj} & {nl} & {nj} & "
                     f"{x['oracle']['ece']:.3f} & {x['jev_oracle']['ece']:.3f} \\\\")
    w = {k: sum(x["cal"][k] < x["jev"][k] for x in rows) for k in KEYS}
    n = len(rows)
    return r"""\begin{table*}[t]
\centering\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{llrrrrrrrrr}
\toprule
 & & \multicolumn{3}{c}{ECE} & \multicolumn{2}{c}{Brier} & \multicolumn{2}{c}{NLL} & \multicolumn{2}{c}{ECE, oracle} \\
\cmidrule(lr){3-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}\cmidrule(lr){10-11}
Task (head) & calibrator & ours raw & ours & Jev & ours & Jev & ours & Jev & ours & Jev \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\caption{Calibration on the test split, our served model (batch size 1) against Jev on the same examples. The calibrator is chosen and fitted on the 200 gold dev examples only (5-fold CV negative log-likelihood) and frozen before a single logged test scoring; Choice and Score heads may only use argmax-preserving calibrators, so no decision changes. Score heads are scored as a distribution over levels (gold rounded to the nearest level). Bold is the better of the two systems. Ours is better on """ + \
        f"{w['ece']}/{n} heads in ECE, {w['brier']}/{n} in Brier score and {w['nll']}/{n} in NLL." + r""" \emph{Oracle} columns recalibrate each system by 5-fold cross-validation on the test labels with the same allowed methods: what any post-hoc recalibration of either system could reach at best.}
\label{tab:cal}
\end{table*}
"""


def figure(rows: list[dict]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.6), gridspec_kw={"width_ratios": [1.5, 1]})
    names = [label(x) for x in rows]
    yy = np.arange(len(rows))[::-1]
    ax = axes[0]
    ax.barh(yy + 0.27, [x["raw"]["ece"] for x in rows], 0.27, color="#c9d6e8", label="ours, raw")
    ax.barh(yy, [x["cal"]["ece"] for x in rows], 0.27, color="#2b6cb0", label="ours, calibrated on dev")
    ax.barh(yy - 0.27, [x["jev"]["ece"] for x in rows], 0.27, color="#d97706", label="Jev")
    ax.set_yticks(yy, names, fontsize=8)
    ax.set_xlabel("ECE (10 bins, lower is better)")
    ax.legend(fontsize=8, loc="upper right")
    ax.spines[["top", "right"]].set_visible(False)
    ax = axes[1]
    picks = [x for x in rows if (x["task"], x["head"]) in {("emotion", "answer"), ("toxic_chat", "toxic"),
                                                            ("prompt_injections", "answer"), ("banking77", "answer")}] or rows[:4]
    cols = ["#2b6cb0", "#16a34a", "#9333ea", "#dc2626"]
    ax.plot([0, 1], [0, 1], color="grey", lw=0.8, ls=":")
    for x, c in zip(picks, cols):
        for key, ls, mk in (("cal", "-", "o"), ("jev", "--", "s")):
            rel = [b for b in x[key]["reliability"] if b["n"] >= 10]
            ax.plot([b["conf"] for b in rel], [b["acc"] for b in rel], ls=ls, marker=mk, ms=3, color=c, lw=1.2,
                    label=f"{label(x)}, {'ours' if key == 'cal' else 'Jev'}")
    ax.set_xlabel("confidence (top label)")
    ax.set_ylabel("accuracy")
    ax.set_xlim(0.0, 1.0)
    ax.set_ylim(0.0, 1.02)
    ax.legend(fontsize=6.5, loc="upper left")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(PAPER / "figures" / f"calibration.{ext}", bbox_inches="tight", dpi=200)


def main() -> Path:
    rows = load()
    out = RESULTS / "CALIBRATION.md"
    out.write_text(markdown(rows))
    (PAPER / "tables" / "calibration.tex").write_text(latex(rows))
    figure(rows)
    return out


if __name__ == "__main__":
    print(main().read_text())
