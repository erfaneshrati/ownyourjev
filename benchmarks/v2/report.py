"""Build benchmarks/results_v2/RESULTS.md: one row per task from final.json, round history, quiet-machine latency.

Verdict per task: win = our 95% bootstrap CI lies entirely above Jev's score on the same examples;
tie = the CI contains Jev's score; loss = the CI lies entirely below. For SummEval/HelpSteer2 (mean over
dimensions, no joint CI) the verdict uses the per-dimension CIs: win only if every dimension wins.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from benchmarks.tasks import MODES
from benchmarks.v2.protocol import RESULTS

QUIET = RESULTS / "_quiet_latency"
# reading comprehension and generated-text judging are work in progress (experiments kept, not reported)
DEFERRED = {"boolq", "summeval", "helpsteer2"}


def _quiet_p95(task: str) -> tuple[float | None, float | None]:
    vals = []
    for p in sorted(QUIET.glob(f"{task}*.json")):
        d = json.loads(p.read_text())
        vals.append((d["cpu_p50_ms"], d["cpu_p95_ms"]))
    if not vals:
        return None, None
    return max(v[0] for v in vals), max(v[1] for v in vals)  # worst of the quiet runs


def verdict(final: dict) -> str:
    h = final["headline"]
    jev = h["jev_same_examples"]
    lo, hi = h.get("ours_ci95") or (math.nan, math.nan)
    if lo is None or (isinstance(lo, float) and math.isnan(lo)):
        wins = losses = 0
        for head, m in final["heads"].items():
            j = final["jev_same_examples"].get(head, {}).get(m["metric"])
            lo_, hi_ = m["ci95"]
            wins += lo_ > j
            losses += hi_ < j
        n = len(final["heads"])
        return "win" if wins == n else ("loss" if h["ours"] < jev else "tie")
    return "win" if lo > jev else ("loss" if hi < jev else "tie")


def main() -> Path:
    log = (RESULTS / "TEST_ACCESS.log").read_text().splitlines()
    rows = []
    for mode in ("noul", "choice", "score"):
        for t in MODES[mode]:
            if t in DEFERRED:
                continue
            fp = RESULTS / t / "final.json"
            if not fp.is_file():
                rows.append((mode, t, None))
                continue
            rows.append((mode, t, json.loads(fp.read_text())))
    lines = ["# ownyourjev v2 results (generated by benchmarks/v2/report.py)", ""]
    lines.append("Jev = jev-1.13.0, re-scored from the paper's per-example responses on exactly our evaluation examples. "
                 "Ours = ~150M encoder trained on LLM labels + 220 gold examples from the training split, all choices made on dev, "
                 "CPU int8/fp32 ONNX. Verdict: win if our 95% bootstrap CI is entirely above Jev, tie if it contains Jev, loss if entirely below. "
                 "Latency = worst p50/p95 over repeated runs on a quiet machine (4 threads, batch 1, all of a task's questions per request); gate p95 < 70 ms.")
    lines += ["", "| type | task | metric | n | ours (95% CI) | Jev | verdict | test looks | CPU p50 / p95 ms | gate |", "|---|---|---|---|---|---|---|---|---|---|"]
    tally = {"win": 0, "tie": 0, "loss": 0}
    for mode, t, f in rows:
        if f is None:
            lines.append(f"| {mode} | {t} | – | – | not finished | – | – | – | – | – |")
            continue
        h = f["headline"]
        v = verdict(f)
        tally[v] += 1
        looks = sum(1 for line in log if f"\t{t}\t" in line)
        lo, hi = h.get("ours_ci95") or (math.nan, math.nan)
        ci = f" ({lo:.3f}–{hi:.3f})" if lo is not None and not (isinstance(lo, float) and math.isnan(lo)) else " (mean of dims)"
        p50, p95 = _quiet_p95(t)
        lat = f"{p50:.0f} / {p95:.0f}" if p95 else "–"
        gate = "pass" if p95 and p95 < 70 else ("fail" if p95 else "–")
        lines.append(f"| {mode} | {t} | {h['metric']} | {f['n_eval']} | {h['ours']:.3f}{ci} | {h['jev_same_examples']:.3f} | **{v}** | {looks} | {lat} | {gate} |")
    lines += ["", f"Tally: {tally['win']} wins, {tally['tie']} ties, {tally['loss']} losses.", "",
              "Work in progress (not reported): " + ", ".join(sorted(DEFERRED)) + ". Their experiments are kept under benchmarks/results_v2/<task>/.", ""]
    # per-head detail for multi-question tasks
    lines += ["## All question heads", "", "| task | head | metric | ours (95% CI) | Jev |", "|---|---|---|---|---|"]
    for mode, t, f in rows:
        if not f:
            continue
        for head, m in f["heads"].items():
            j = f["jev_same_examples"].get(head, {}).get(m["metric"])
            lines.append(f"| {t} | {head} | {m['metric']} | {m[m['metric']]:.3f} ({m['ci95'][0]:.3f}–{m['ci95'][1]:.3f}) | {j:.3f} |" if j is not None else f"| {t} | {head} | {m['metric']} | {m[m['metric']]:.3f} | – |")
    shown = [ln for ln in log if not any(f"\t{d}\t" in ln for d in DEFERRED)]
    lines += ["", "## Round history (every test look of the reported tasks)", "", "```", *shown, "```", ""]
    out = RESULTS / "RESULTS.md"
    out.write_text("\n".join(lines))
    return out


if __name__ == "__main__":
    print(main().read_text())
