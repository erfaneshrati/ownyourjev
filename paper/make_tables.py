# ---- test-access log (12 reported tasks)
rows, analyses = [], {}
for line in open("benchmarks/results_v2/TEST_ACCESS.log"):
    p = line.rstrip("\n").split("\t")
    if len(p) > 2 and p[2].startswith("analysis=") and (p[1] in NAMES or p[1] == "ALL"):
        k = p[2].split("=", 1)[1]
        analyses[k] = analyses.get(k, 0) + 1
        continue
    if len(p) < 5 or p[1] not in NAMES:
        continue
    ts, task, _, ours, jev = p[:5]
    reason = p[5].split("=", 1)[1].strip("'") if len(p) > 5 else ""
    kind = "first scoring" if not reason else ("re-score (latency gate)" if task == "toxic_chat" else "re-score (dev-gated)")
    rows.append(f"{ts.replace('T', ' ')[:16]} & {NAMES[task]} & {float(ours.split('=')[1]):.4f} & {float(jev.split('=')[1]):.4f} & {kind} \\\\")
log = r"""\begin{table}[h]
\centering\small
\begin{tabular}{llrrl}
\toprule
Time & Task & Ours & Jev & Kind \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\caption{Every test scoring of the 12 reported tasks, from the audited log. The log also records """ + f"{sum(analyses.values())}" + r""" analysis-only accesses (calibration, batch-1 serving, oracle recompute, de-duplication) (Section~\ref{sec:calibration}), none of which changed a model, a threshold or a decision.}
\label{tab:log}
\end{table}
"""
open("paper/tables/testlog.tex", "w").write(log)
print(len(rows), "test-log rows")

