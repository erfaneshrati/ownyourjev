import json
F = json.load(open("paper/facts.json")); T = F["tasks"]
NAMES = {"sms_spam": "SMS Spam", "paws": "PAWS", "prompt_injections": "Prompt Injections", "toxic_chat": "ToxicChat",
         "banking77": "Banking77", "clinc150": "CLINC150", "ag_news": "AG News", "financial_phrasebank": "Financial PhraseBank",
         "emotion": "Emotion", "stsb": "STS-B", "sst5": "SST-5", "toxigen": "ToxiGen"}
MET = {"f1": "F1", "accuracy": "Acc.", "spearman": "Spearman", "argmax_accuracy": "Acc."}
TYPE = {"noul": "Noul", "choice": "Choice", "score": "Score"}
order = ["sms_spam", "paws", "prompt_injections", "toxic_chat", "banking77", "clinc150", "ag_news", "financial_phrasebank", "emotion", "stsb", "sst5", "toxigen"]
def b(s, cond): return f"\\textbf{{{s}}}" if cond else s
rows = []
for t in order:
    x = T[t]; win = x["verdict"] == "win"
    rows.append(f"{TYPE[x['mode']]} & {NAMES[t]} & {MET[x['metric']]} & {x['n']:,} & {b(f'{x[chr(111)+chr(117)+chr(114)+chr(115)]:.3f}', win)} {{\\scriptsize[{x['ci'][0]:.3f}, {x['ci'][1]:.3f}]}} & {x['jev']:.3f} & {x['verdict']} & {x['looks']} \\\\")
main = r"""\begin{table*}[t]
\centering\small
\begin{tabular}{llllrlcc}
\toprule
Type & Task & Metric & $n_{\text{test}}$ & Ours [95\% CI] & Jev & Verdict & Test looks \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\caption{Main results. Ours: a $\sim$150M-parameter encoder trained on LLM labels plus a 220-example human-label budget, served as ONNX on CPU. Jev: \texttt{jev-1.13.0} re-scored from its published per-example responses on exactly the same test examples. Verdict: \emph{win} if our 95\% bootstrap CI lies entirely above Jev, \emph{tie} if it contains Jev. \emph{Test looks} counts how often the test split was scored for the task; second looks were permitted only after a dev-gated improvement (Section~\ref{sec:protocol}). For ToxicChat the headline is the toxic head; its jailbreak head scores """ + f"{T['toxic_chat']['heads']['jailbreak']['ours']:.3f} vs.\\ Jev {T['toxic_chat']['heads']['jailbreak']['jev']:.3f}" + r""". For ToxiGen the second (toxicity) head scores Spearman """ + f"{T['toxigen']['heads']['toxicity']['ours']:.3f} vs.\\ {T['toxigen']['heads']['toxicity']['jev']:.3f}" + r""".}
\label{tab:main}
\end{table*}
"""
open("paper/tables/main.tex", "w").write(main)

